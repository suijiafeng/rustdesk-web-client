import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { pbjs, pbts } from 'protobufjs-cli';
import { PROTO_SOURCE } from '../shared/protoSource.ts';

const outputFile = fileURLToPath(new URL('../shared/protoTypes.generated.d.ts', import.meta.url));
const directory = await mkdtemp(path.join(tmpdir(), 'rd-proto-types-'));
const generate = (tool: typeof pbjs, args: string[]) => new Promise<string>((resolve, reject) => {
  tool.main(args, (error, output) => {
    if (error) reject(error);
    else if (typeof output !== 'string') reject(new Error('Protobuf generator returned no output'));
    else resolve(output);
  });
});

try {
  const sourceFile = path.join(directory, 'rustdesk.proto');
  const javascriptFile = path.join(directory, 'rustdesk.js');
  await writeFile(sourceFile, PROTO_SOURCE);
  await writeFile(javascriptFile, await generate(pbjs, [
    '--target', 'static-module', '--wrap', 'esm', '--root', 'rustdeskWeb',
    '--keep-case', '--no-service', sourceFile,
  ]));
  const declarations = await generate(pbts, ['--no-comments', javascriptFile]);
  // The installed pbts emits $Properties with optional oneof selector unions,
  // matching toObject({ oneofs: true }) without handwritten schema patches.
  const output = `// Generated by yarn proto:types from shared/protoSource.ts. Do not edit.\n${declarations}`;
  if (process.argv.includes('--check')) {
    if (await readFile(outputFile, 'utf8') !== output) {
      throw new Error('Protocol declarations are stale; run yarn proto:types');
    }
  } else await writeFile(outputFile, output);
} finally {
  await rm(directory, { recursive: true, force: true });
}
