export type Locale = 'en' | 'zh';
export type LocalePreference = 'default' | 'en' | 'zh';

export const LOCALE_STORAGE_KEY = 'rd_web_locale';

export function resolveLocalePreference(saved: string | null | undefined): LocalePreference {
  if (saved === 'zh' || saved === 'en' || saved === 'default') {
    return saved;
  }
  return 'default';
}

export function detectSystemLocale(navLang?: string | null): Locale {
  if (navLang && /^zh\b/i.test(navLang.trim())) {
    return 'zh';
  }
  return 'en';
}

export function resolveEffectiveLocale(
  pref: LocalePreference,
  navLang?: string | null,
): Locale {
  if (pref === 'default') {
    return detectSystemLocale(navLang);
  }
  return pref;
}

